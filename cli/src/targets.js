/* The brief folders that carry the complex-md name, such as
   .claude/rules/complex-md. No other tool writes into them, so wire and
   unwire remove each one once it is empty, also when an earlier version
   created it and no manifest records it. A shared folder such as
   .clinerules goes only when the manifest records that wire created it. */
export const OWN_BRIEF_DIRS = Object.values(BRIEF_SPECS).filter((s) => !s.prefix).map((s) => s.dir);

/* The files one spec produces for these briefs, as relative path to
   content. Pure, so check can compute it without writing anything. */
export function briefFiles(spec, briefs) {
  const out = new Map();
  for (const b of briefs) out.set(`${spec.dir}/${spec.prefix || ''}${b.slug}${spec.ext}`, withNotice(spec.header(b) + b.text));
  return out;
}

/* Whether a relative path is one this spec owns: directly in its folder,
   with its prefix and extension. */
export function specOwns(spec, rel) {
  const head = `${spec.dir}/${spec.prefix || ''}`;
  return rel.startsWith(head) && rel.endsWith(spec.ext) && !rel.slice(spec.dir.length + 1).includes('/');
}

function writeSpec(ctx, spec) {
  writeBriefs(ctx, spec);
}

/**
 * The target table. Each target may implement:
 *   detect(root)      repo markers that opt it in when --for is not given
 *   rules(ctx)        path-scoped rule file
 *   hooks(ctx)        deterministic edit gates
 *   mcp(ctx)          MCP server registration
 * ctx = { root, inv, block, paths, briefs, report, log, carried }. All writers are
 * idempotent: existing entries are recognized, never duplicated.
 */
export const TARGETS = {
  claude: {
    detect: (root) => existsSync(join(root, '.claude')) || existsSync(join(root, 'CLAUDE.md')),
    rules(ctx) {
      // CLAUDE.md always carries the block once wire has run: appended,
      // imported from AGENTS.md, or written when CLAUDE.md is created.
      dropBlockCopy(ctx, '.claude/rules/complex-md.md');
      writeSpec(ctx, BRIEF_SPECS.claude);
    },
    hookFile: '.claude/settings.json',
    /* `local`: the per user .claude/settings.local.json, which Claude Code
       merges over the committed settings. */
    hooks(ctx) {
      const { root, inv, report, local } = ctx;
      const rel = local ? '.claude/settings.local.json' : '.claude/settings.json';
      editJson(ctx, rel, 'claude-hooks', (s) => {
        s.hooks ||= {};
        const inner = (list) => (list || []).flatMap((g) => g.hooks || []);
        if (pinLegacy(inner(s.hooks.PreToolUse), 'hook pre', inv)) report.hooks.push(`${rel} PreToolUse (pinned)`);
        if (pinLegacy(inner(s.hooks.Stop), 'hook stop', inv)) report.hooks.push(`${rel} Stop (pinned)`);
        if (!hasHook(s.hooks.PreToolUse, 'hook pre')) {
          (s.hooks.PreToolUse ||= []).push({ matcher: 'Edit|Write|MultiEdit|NotebookEdit', hooks: [{ type: 'command', command: hookCommand(inv, 'hook pre'), timeout: 30 }] });
          report.hooks.push(`${rel} PreToolUse`);
        }
        if (!hasHook(s.hooks.Stop, 'hook stop')) {
          (s.hooks.Stop ||= []).push({ hooks: [{ type: 'command', command: hookCommand(inv, 'hook stop'), timeout: 60 }] });
          report.hooks.push(`${rel} Stop`);
        }
      });
      if (local) keepOutOfGit(root, rel);
    },
    mcp(ctx) {
      const { mcpInv } = ctx;
      addMcpJson(ctx, '.mcp.json', { command: mcpInv.command, args: [...mcpInv.args, 'mcp'] });
    },
  },

  cursor: {
    detect: (root) => existsSync(join(root, '.cursor')),
    rules(ctx) {
      const { block, paths } = ctx;
      blockRule(ctx, '.cursor/rules/complex-md.mdc', `---\ndescription: COMPLEX.md structural risk map\nglobs: ${paths.map(literalGlob).join(', ')}\nalwaysApply: false\n---\n${block}`);
      writeSpec(ctx, BRIEF_SPECS.cursor);
    },
    hookFile: '.cursor/hooks.json',
    hooks(ctx) {
      const { inv, report, local } = ctx;
      // Cursor reads hooks from the project file or the user's home, and
      // has no per user file inside the project.
      if (local) return void report.skipped.push('.cursor/hooks.json (Cursor has no per user project hooks file; --hooks without --local writes it)');
      editJson(ctx, '.cursor/hooks.json', 'cursor-hooks', (h) => {
        h.version ||= 1;
        h.hooks ||= {};
        if (pinLegacy(h.hooks.preToolUse || [], 'hook cursor-pre', inv)) report.hooks.push('.cursor/hooks.json preToolUse (pinned)');
        if (pinLegacy(h.hooks.stop || [], 'hook cursor-stop', inv)) report.hooks.push('.cursor/hooks.json stop (pinned)');
        if (!(h.hooks.preToolUse || []).some((x) => isOurs(x.command, 'hook cursor-pre'))) {
          (h.hooks.preToolUse ||= []).push({ command: hookCommand(inv, 'hook cursor-pre'), matcher: 'Write|StrReplace|Edit|MultiEdit|SearchReplace|Delete', timeout: 30 });
          report.hooks.push('.cursor/hooks.json preToolUse');
        }
        if (!(h.hooks.stop || []).some((x) => isOurs(x.command, 'hook cursor-stop'))) {
          (h.hooks.stop ||= []).push({ command: hookCommand(inv, 'hook cursor-stop'), timeout: 60, loop_limit: 1 });
          report.hooks.push('.cursor/hooks.json stop');
        }
      });
    },
    mcp(ctx) {
      const { mcpInv } = ctx;
      addMcpJson(ctx, '.cursor/mcp.json', { command: mcpInv.command, args: [...mcpInv.args, 'mcp'] });
    },
  },

  /* OpenHands path triggered rules (docs.openhands.dev, Agent Skills spec;
     OpenHands is MIT). A rule at .agents/skills/<name>.md with a `paths:`
     list is injected when the agent reads, edits or creates a matching file,
     once per conversation, and is not advertised to the model. That is the
     per path brief, arrived at independently, so each brief becomes one rule.
     The files are prefixed complex-md- because .agents/skills/ is the user's
     directory too and only ours may be cleared. */
  openhands: {
    /* Only .openhands/: .agents/ is shared by Codex, Antigravity, Copilot,
       OpenClaw and Hermes, and is no sign of OpenHands. */
    detect: (root) => isDir(join(root, '.openhands')),
    rules(ctx) {
      const { block, paths } = ctx;
      blockRule(ctx, '.agents/skills/complex-md.md', `---\nname: complex-md\npaths:\n${paths.map((p) => `  - ${JSON.stringify(literalGlob(p))}`).join('\n')}\n---\n${block}`);
      writeSpec(ctx, BRIEF_SPECS.openhands);
    },
  },

  /* Antigravity workspace rules (antigravity.google/docs/rules). Every .md
     file directly in .agents/rules/ needs front matter with a `trigger`; a
     `glob` trigger loads the rule when the agent reads or edits a file that
     `globs` matches. Files in subfolders are ignored, so the briefs sit flat
     with the complex-md- prefix, and only prefixed files are cleared.
     Detected from .agents/rules/ itself: .agents/ alone is shared by
     several agents. */
  antigravity: {
    detect: (root) => existsSync(join(root, '.agents/rules')),
    rules(ctx) {
      writeSpec(ctx, BRIEF_SPECS.antigravity);
    },
  },

  codex: {
    detect: (root) => existsSync(join(root, '.codex')),
    mcp({ root, mcpInv, report, mark }) {
      const p = join(root, '.codex/config.toml');
      const existed = existsSync(p);
      const cur = existed ? readFileSync(p, 'utf8') : '';
      /* A table outside the markers is one an earlier version appended, or
         the user's own; either way it stays, and no second one is added. */
      if (/\[mcp_servers\.complex-md\]/.test(outsideRegion(cur))) return;
      const args = [...mcpInv.args, 'mcp'];
      const table = `[mcp_servers.complex-md]\ncommand = ${JSON.stringify(mcpInv.command)}\nargs = [${args.map((a) => JSON.stringify(a)).join(', ')}]\n`;
      if (mark('.codex/config.toml', table, { style: 'hash', create: true, created: !existed }) === 'written') report.mcp.push('.codex/config.toml');
    },
  },

  /* GitHub Copilot path instructions (docs.github.com, "Adding repository
     custom instructions"). A file under .github/instructions/ named
     *.instructions.md, with an `applyTo` glob in its front matter, is read
     by Copilot code review and the Copilot cloud agent for the files that
     glob matches. Code review reads it from the pull request's head
     branch, so each brief reaches the review of every change to its file
     with nothing installed by the reviewer. Subfolders are allowed, so the
     briefs get a folder that is ours alone. Detected from Copilot's own
     files, never from .github/, which nearly every repository has. */
  copilot: {
    detect: (root) => existsSync(join(root, '.github/copilot-instructions.md')) || existsSync(join(root, '.github/instructions')),
    rules(ctx) {
      writeSpec(ctx, BRIEF_SPECS.copilot);
    },
  },

  /* Claude Code Review reads REVIEW.md at the repository root and puts a
     root file in place of a line that holds only `@` and its name
     (code.claude.com, "Customize Code Review"). It does so only when it
     reads REVIEW.md from a protected branch, at most 8 files and 150,000
     bytes in all; otherwise the line stays plain text. REVIEW.md belongs to the
     team, so wire adds that one line to a file that exists and never
     creates one. A line inside an open code fence or HTML comment would
     stay plain text, so an ending like that gets nothing. */
  review: {
    detect: (root) => existsSync(join(root, 'REVIEW.md')),
    rules(ctx) {
      const { root, report, mark } = ctx;
      const p = join(root, 'REVIEW.md');
      if (!existsSync(p)) return void report.skipped.push('REVIEW.md (absent, not created)');
      const cur = readFileSync(p, 'utf8');
      const outside = outsideRegion(cur);
      if (/^@COMPLEX\.md\s*$/m.test(outside)) return void report.skipped.push('REVIEW.md');
      const fences = (outside.match(/^\s*(```|~~~)/gm) || []).length;
      if (fences % 2 || outside.lastIndexOf('<!--') > outside.lastIndexOf('-->')) {
        return void report.skipped.push('REVIEW.md (ends inside a code fence or comment)');
      }
      const r = mark('REVIEW.md', '@COMPLEX.md\n');
      if (r === 'written') report.primary.push('REVIEW.md (@COMPLEX.md include)');
      else report.skipped.push('REVIEW.md');
    },
  },

  /* Devin Desktop, formerly Windsurf (docs.devin.ai, Cascade memories and
     rules). Workspace rules live in .devin/rules/*.md, with
     .windsurf/rules/*.md as the fallback, at most 12,000 characters each.
     A `glob` trigger applies a rule when the agent reads or edits a file
     that `globs` matches. Each target writes its own folder flat, with the
     complex-md- prefix, and clears only prefixed files. */
  devin: {
    detect: (root) => existsSync(join(root, '.devin')),
    rules(ctx) {
      writeSpec(ctx, BRIEF_SPECS.devin);
    },
  },

  /* Kiro steering (kiro.dev/docs/steering). A file in .kiro/steering/ with
     `inclusion: fileMatch` loads when a file that `fileMatchPattern`
     matches is in the conversation. The folder holds the user's own
     steering too, so the briefs carry the complex-md- prefix and only
     prefixed files are cleared. */
  kiro: {
    detect: (root) => existsSync(join(root, '.kiro')),
    rules(ctx) {
      writeSpec(ctx, BRIEF_SPECS.kiro);
    },
  },

  windsurf: {
    detect: (root) => existsSync(join(root, '.windsurf')),
    rules(ctx) {
      const { block, paths } = ctx;
      blockRule(ctx, '.windsurf/rules/complex-md.md', `---\ntrigger: glob\nglobs: ${paths.map(literalGlob).join(', ')}\n---\n${block}`);
      writeSpec(ctx, BRIEF_SPECS.windsurf);
    },
  },

  /* Cline conditional rules (docs.cline.bot, Cline rules). A file in
     .clinerules/ whose front matter carries a `paths:` list of globs
     applies when the agent works on a matching file. The folder is the
     user's too, so the briefs carry the complex-md- prefix. An older Cline
     layout is a single .clinerules FILE; that is not a folder to write
     into, so it is neither detected nor touched. */
  cline: {
    detect: (root) => isDir(join(root, '.clinerules')),
    rules(ctx) {
      const { root, block, report } = ctx;
      if (existsSync(join(root, '.clinerules')) && !isDir(join(root, '.clinerules'))) {
        return void report.skipped.push('.clinerules (a file, not a folder)');
      }
      blockRule(ctx, '.clinerules/complex-md.md', block);
      writeSpec(ctx, BRIEF_SPECS.cline);
    },
  },

  /* Roo Code reads AGENTS.md and offers no path scoped rule, so a file here
     could only repeat the block. The target stays so `--for roo` keeps
     working and a rewire removes the copy earlier versions wrote. It is
     retired: --help does not offer it. */
  roo: {
    retired: true,
    detect: (root) => existsSync(join(root, '.roo')),
    rules(ctx) {
      dropBlockCopy(ctx, '.roo/rules/complex-md.md');
    },
  },

  // Global-config targets. Their MCP registry lives per machine, so the
  // registration carries the repo root explicitly (`mcp --root <path>`);
  // the server does not depend on the launch cwd.
  openclaw: {
    global: true,
    rules: writeSkill,
    mcp({ root, mcpInv, report, log }) {
      const args = ['mcp', 'add', 'complex-md', '--command', mcpInv.command, ...[...mcpInv.args, 'mcp', '--root', root].flatMap((a) => ['--arg', a])];
      if (cliAvailable('openclaw')) {
        try {
          execFileSync('openclaw', args, { stdio: 'pipe' });
          report.mcp.push('openclaw (global registry)');
          return;
        } catch (e) {
          log(`openclaw mcp add failed (${String(e.message).split('\n')[0]}); register manually:`);
        }
      } else {
        log('openclaw CLI not found; register manually:');
      }
      log(`  openclaw ${args.map((a) => (/\s/.test(a) ? JSON.stringify(a) : a)).join(' ')}`);
    },
  },

  hermes: {
    global: true,
    rules(ctx) {
      writeSkill(ctx);
      ctx.log('hermes loads project skills once the repository is trusted: run `hermes skills trust` in it.');
    },
    mcp({ root, mcpInv, report, log }) {
      const command = `${mcpInv.shell} mcp --root ${root}`;
      if (cliAvailable('hermes')) {
        try {
          execFileSync('hermes', ['mcp', 'add', 'complex-md', '--command', command], { stdio: 'pipe' });
          report.mcp.push('hermes (global registry)');
          return;
        } catch (e) {
          log(`hermes mcp add failed (${String(e.message).split('\n')[0]}); register manually:`);
        }
      } else {
        log('hermes CLI not found; register manually:');
      }
      log(`  hermes mcp add complex-md --command "${command}"`);
    },
  },
};

